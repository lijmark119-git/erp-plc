export function hasPermission(user, permission, permissionMap = DEFAULT_ROLE_PERMISSIONS) {
  if (!user || typeof permission !== 'string' || !permission) return false;
  const role = String(user.role || '').toUpperCase();
  const rolePermissions = typeof permissionMap.get === 'function'
    ? permissionMap.get(role) ?? permissionMap.get(String(user.role || ''))
    : permissionMap[role];
  return rolePermissions?.has(permission) ?? false;
}

export function requirePermission(permission, permissionMap = DEFAULT_ROLE_PERMISSIONS) {
  return (req, res, next) => {
    if (!hasPermission(req.user, permission, permissionMap)) {
      return res.status(403).json({ error: 'Forbidden. You do not have permission for this action.' });
    }

    return next();
  };
}
